def _exercise(
    name: str,
    pattern: MovementPattern,
    primary: tuple[MuscleGroup, ...],
    secondary: tuple[MuscleGroup, ...],
    equipment: tuple[Equipment, ...],
    difficulty: int,
    *,
    unilateral: bool = False,
    tags: tuple[ContraindicationTag, ...] = (),
    substitutions: tuple[str, ...] = (),
    en: tuple[str, ...] = (),
    es: tuple[str, ...] = (),
    key: str | None = None,
) -> Exercise:
    exercise_key = key or name.lower().replace("-", "_").replace(" ", "_").replace("'", "")
    return Exercise(
        exercise_id=f"ex.{exercise_key}",
        canonical_name=name,
        movement_pattern=pattern,
        primary_muscles=primary,
        secondary_muscles=secondary,
        equipment=equipment,
        unilateral=unilateral,
        technical_difficulty=difficulty,
        contraindication_tags=tags,
        substitutions=tuple(f"ex.{item}" for item in substitutions),
        aliases=(*(Alias("en", text) for text in en), *(Alias("es", text) for text in es)),
    )



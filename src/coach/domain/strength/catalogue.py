"""Exercise catalogue 1.0.0: the reference data shipped with the application (strength spec 3).

Every movement pattern is covered; substitutions share their exercise's pattern. A new
version may add exercises and aliases, but never reuses or removes an ID: recorded sets
refer to it.
"""


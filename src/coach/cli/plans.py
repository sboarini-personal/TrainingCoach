"""``coach plan`` commands (P12; planning spec 2 and 3): list plans and their versions, show a
version, and the athlete's explicit activation or rejection of a PROPOSED version. Content is
shown as stored; this module only formats it."""

from __future__ import annotations

import argparse
from datetime import date, timedelta
from typing import TextIO
from uuid import UUID

from coach.application.consent import ConsentRequiredError
from coach.application.errors import ConcurrencyConflictError, NotFoundError
from coach.application.ownership import OwnerScope
from coach.application.plans import PlanNotReadyError
from coach.application.policy_gate import PolicyDeniedError
from coach.cli.activities import CONSENT_HINT, TIMEZONE_HINT, CommandError
from coach.cli.runtime import Runtime, TimezoneRequiredError
from coach.domain.common.errors import DomainValidationError, InvalidTransitionError
from coach.domain.common.time import DateRange
from coach.domain.onboarding.readiness import LABELS
from coach.domain.plans.adaptation import AdaptationDecision, AdaptationTrigger
from coach.domain.plans.plan import PlanVersion
from coach.domain.plans.workout import PlannedWorkout

TRIGGERS = {item.value.lower().replace("_", "-"): item for item in AdaptationTrigger}


def add_parsers(commands: argparse._SubParsersAction[argparse.ArgumentParser]) -> None:
    plan = commands.add_parser("plan", help="training plans").add_subparsers(
        dest="action", required=True
    )
    generate = plan.add_parser(
        "generate", help="propose a plan version for your goal (generator rules 1.0.0)"
    )
    generate.add_argument("--goal", help="the goal ID; default: your primary goal")
    plan.add_parser("list", help="your plans and their versions")
    show = plan.add_parser("show", help="a plan version (default: the ACTIVE one)")
    show.add_argument("plan_id", nargs="?")
    show.add_argument("--version", type=int, help="default: ACTIVE, else the latest")
    activate = plan.add_parser("activate", help="activate a PROPOSED version")
    activate.add_argument("plan_id")
    activate.add_argument("version", type=int)
    activate.add_argument(
        "--revision",
        type=int,
        required=True,
        help="the plan revision you reviewed (from plan list)",
    )
    activate.add_argument("--reason", help="why you activate it (optional)")
    reject = plan.add_parser("reject", help="reject a PROPOSED version")
    reject.add_argument("plan_id")
    reject.add_argument("version", type=int)
    done = plan.add_parser("executions", help="planned versus done, a week at a time")
    done.add_argument(
        "--week", type=date.fromisoformat, help="any date of the week; default: this week"
    )
    adapt = plan.add_parser("adapt", help="run the adaptive loop on your ACTIVE plan")
    adapt.add_argument(
        "--trigger",
        default="athlete-request",
        choices=sorted(TRIGGERS),
        help="what prompted it (default: your request)",
    )
    plan.add_parser("decisions", help="the adaptive loop's decisions and their reasons")
    link = plan.add_parser("link", help="link an activity to a planned workout")
    link.add_argument("activity_id")
    link.add_argument("workout_id", help="a workout of the ACTIVE plan, or none (unplanned)")


def _minutes(seconds: float | None) -> str:
    return "" if seconds is None else f" {round(seconds / 60)} min"


def _workout(item: PlannedWorkout) -> str:
    sport = "" if item.sport is None else f" {item.sport.value}"
    effort = "" if item.max_rpe is None else f" up to RPE {item.max_rpe:g}"
    key = " [key]" if item.is_key else ""
    return f"{item.type.value}{sport}{_minutes(item.planned_seconds)}{effort}{key}: {item.what}"


def _show(version: PlanVersion, out: TextIO) -> None:
    content = version.content
    parent = "" if version.parent_number is None else f" (from version {version.parent_number})"
    print(
        f"plan {version.plan_id} version {version.number}{parent}: {version.status.value}",
        file=out,
    )
    print(
        f"{content.start} to {content.end}, generated by {version.generator.kind.value}", file=out
    )
    if content.provisional:
        print("PROVISIONAL: built on assumptions", file=out)
        for assumption in content.assumptions:
            print(f"  assumption: {assumption}", file=out)
    for week in content.weeks:
        print(
            f"week {week.week_index} ({week.start}, {week.phase.value}): {week.primary_goal}",
            file=out,
        )
        for offset, workouts in enumerate(week.days):
            day = week.start + timedelta(days=offset)
            for item in workouts:
                print(f"  {day} {day:%a}  {_workout(item)}", file=out)
    print(f"content hash {version.content_hash}", file=out)


def plan(runtime: Runtime, scope: OwnerScope, args: argparse.Namespace, out: TextIO) -> int:
    plans = runtime.plans
    try:
        match args.action:
            case "list":
                headers = plans.plans(scope)
                if not headers:
                    print("no plans yet", file=out)
                for header in headers:
                    active = "none" if header.active_number is None else header.active_number
                    print(
                        f"{header.plan_id}  goal {header.goal_id}  revision {header.version}  "
                        f"active version {active}",
                        file=out,
                    )
                    for item in plans.versions(scope, header.plan_id):
                        print(
                            f"  version {item.number}  {item.status.value}  "
                            f"{item.content.start} to {item.content.end}",
                            file=out,
                        )
                return 0
            case "adapt":
                result = runtime.adaptation.run(scope, TRIGGERS[args.trigger])
                _decision(result.decision, out)
                if result.proposed is not None:
                    plan_id, number = result.proposed.plan_id, result.proposed.number
                    revision = runtime.plans.plan(scope, plan_id).version
                    print(
                        f"proposed: plan {plan_id} version {number}; review it, then: "
                        f"coach plan activate {plan_id} {number} --revision {revision}",
                        file=out,
                    )
                return 0
            case "decisions":
                history = runtime.adaptation.decisions(scope)
                if not history:
                    print("no decisions yet", file=out)
                for decision in history:
                    _decision(decision, out)
                return 0
            case "executions":
                return _executions(runtime, scope, args.week, out)
            case "link":
                workout = None if args.workout_id == "none" else UUID(args.workout_id)
                linked = runtime.executions.link(scope, UUID(args.activity_id), workout)
                target = "unplanned" if linked.planned_workout_id is None else str(workout)
                print(f"activity {linked.activity_id} linked: {target}", file=out)
                return 0
            case "generate":
                made = runtime.generation.generate(
                    scope, None if args.goal is None else UUID(args.goal)
                )
                _show(made, out)
                print(
                    f"review it, then: coach plan activate {made.plan_id} {made.number} "
                    f"--revision {runtime.plans.plan(scope, made.plan_id).version}",
                    file=out,
                )
                return 0
            case "show":
                found = _selected(runtime, scope, args)
                if found is None:
                    print("no plan to show", file=out)
                    return 0
                _show(found, out)
                return 0
            case "activate":
                changed = plans.activate(
                    scope,
                    UUID(args.plan_id),
                    args.version,
                    expected_revision=args.revision,
                    reason=args.reason,
                )
            case _:
                changed = plans.reject(scope, UUID(args.plan_id), args.version)
    except PlanNotReadyError as missing:
        names = ", ".join(LABELS[item] for item in missing.missing)
        raise CommandError(
            f"not ready for a plan; missing: {names} (see coach readiness)"
        ) from None
    except PolicyDeniedError as denied:
        raise CommandError("denied by policy: " + denial(denied)) from None
    except TimezoneRequiredError:
        raise CommandError(TIMEZONE_HINT) from None
    except ConsentRequiredError:
        raise CommandError(CONSENT_HINT) from None
    except NotFoundError:
        raise CommandError("plan, version, workout or activity not found") from None
    except ConcurrencyConflictError:
        raise CommandError("the plan changed since you reviewed it; run plan list again") from None
    except (DomainValidationError, InvalidTransitionError, ValueError) as error:
        raise CommandError(str(error)) from None
    print(f"plan {changed.plan_id} version {changed.number} is {changed.status.value}", file=out)
    return 0


def denial(denied: PolicyDeniedError) -> str:
    """The reasons of a denial: codes with their day or exercise, each once."""
    shown: list[str] = []
    for reason in denied.decision.reasons:
        where = [value for name in ("day", "exerciseId") if (value := reason.parameter(name))]
        text = reason.code + (f" ({', '.join(where)})" if where else "")
        if text not in shown:
            shown.append(text)
    return "; ".join(shown)


def _decision(item: AdaptationDecision, out: TextIO) -> None:
    reasons = ", ".join(reason.value for reason in item.reasons)
    print(
        f"{item.training_day}  {item.decision.value} ({reasons}; confidence "
        f"{item.confidence.value})",
        file=out,
    )
    print(f"  {item.interpretation}", file=out)
    if item.uncertainty_reasons:
        uncertain = ", ".join(sorted(reason.value for reason in item.uncertainty_reasons))
        print(f"  uncertainty: {uncertain}", file=out)
    for ref in item.evidence:
        note = "" if ref.note is None else f" ({ref.note})"
        print(f"  evidence: {ref.kind.value} {ref.ref_id}{note}", file=out)


def _executions(runtime: Runtime, scope: OwnerScope, week: date | None, out: TextIO) -> int:
    day = runtime.recovery.today(scope) if week is None else week
    monday = day - timedelta(days=day.isoweekday() - 1)
    found = runtime.executions.executions(scope, DateRange(monday, monday + timedelta(days=6)))
    active = runtime.plans.active(scope)
    print(f"week of {monday}: {len(found)} executions", file=out)
    for item in found:
        workout = (
            None
            if item.planned_workout_id is None or active is None
            else active.content.workout(item.planned_workout_id)
        )
        what = "an activity not in the plan" if workout is None else _workout(workout)
        ratios = [
            f"{name} {round(value * 100)}%"
            for name, value in (
                ("duration", item.compliance.duration_ratio),
                ("distance", item.compliance.distance_ratio),
            )
            if value is not None
        ]
        rpe = [] if item.session_rpe is None else [f"RPE {item.session_rpe:g}"]
        extra = ", ".join(ratios + rpe + (["linked by you"] if item.manual else []))
        print(
            f"{item.training_day} {item.training_day:%a}  {item.status.value:<9}  {what}"
            + (f" ({extra})" if extra else ""),
            file=out,
        )
        if item.planned_workout_id is not None:
            print(f"    workout {item.planned_workout_id}", file=out)
        for activity in item.completed_activity_ids:
            print(f"    activity {activity}", file=out)
    return 0


def _selected(runtime: Runtime, scope: OwnerScope, args: argparse.Namespace) -> PlanVersion | None:
    plans = runtime.plans
    if args.plan_id is None:
        active = plans.active(scope)
        if active is not None and args.version is None:
            return active
        header = plans.latest_plan(scope)
    else:
        header = plans.plan(scope, UUID(args.plan_id))
    if header is None:
        return None
    number = args.version or header.active_number or header.latest_number
    return plans.version(scope, header.plan_id, number)
